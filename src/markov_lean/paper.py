def write(b: Build, paper: str | Path, stamp: str | None = None) -> list[Item]:
    """Write what ``build`` made into ``<paper>/figures``; return one ``Item`` per output."""
    from . import figures as fg

    paper = Path(paper)
    out = paper / "figures"
    out.mkdir(parents=True, exist_ok=True)
    prev = out / "preview"
    items: list[Item] = []
    for name in FIGURES:
        if name in b.withheld:
            (out / f"{name}.pdf").unlink(missing_ok=True)  # always generated; the paper skips the figure without it
            items.append(Item(name, "figure", "withheld", "", b.withheld[name]))
        elif name in b.figures:
            fig, source, note = b.figures[name]
            fg.save_pdf(fig, out / f"{name}.pdf")
            items.append(Item(name, "figure", "real", source, note))
        elif name in b.figure_files:  # drawn by its own command; copied as it is
            srcfile, source, note = b.figure_files[name]
            shutil.copyfile(srcfile, out / f"{name}.pdf")
            items.append(Item(name, "figure", "real", source, note))
        elif (out / f"{name}.pdf").exists():
            items.append(Item(name, "figure", "earlier", "", "real figure from an earlier build, not redrawn now"))
        else:
            items.append(Item(name, "figure", "preview" if (prev / f"{name}.pdf").exists() else "missing"))
    _close()
    for name in TABLES:
        tex, source, real = b.tables[name]
        path = out / f"{name}.tex"
        if real:
            path.write_text(HEADER + (f" on {stamp}" if stamp else "") + f" from {source}.\n" + tex)
            n_tbd = tex.count(r"\tbd")
            items.append(Item(name, "table", "real", source, f"{n_tbd} cells still waiting" if n_tbd else ""))
        else:
            if path.exists() and _is_generated(path):
                path.unlink()
            items.append(Item(name, "table", "preview"))
    path = out / "results_macros.tex"
    if b.macros:
        path.write_text(macros_tex(b.macros, stamp, b.macro_names))
    elif path.exists() and _is_generated(path):
        path.unlink()
    for name in b.macro_names:
        if name in b.macros:
            items.append(Item(name, "number", "real", b.macros[name][1], b.macros[name][0]))
        else:
            items.append(Item(name, "number", "preview"))
    for dest, (srcfile, source) in b.copies.items():
        shutil.copyfile(srcfile, out / dest)
        items.append(Item(dest, "extra", "real", source, "not used by the text yet"))
    return items


def format_status(items: list[Item], failures: dict[str, str] | None = None) -> str:
    lines = []
    for kind in ("figure", "table", "number", "extra"):
        sub = [i for i in items if i.kind == kind]
        if not sub:
            continue
        n_real = sum(i.status == "real" for i in sub)
        lines.append(f"{kind}s: {n_real} of {len(sub)} real")
        waiting = [i.name for i in sub if kind == "number" and i.status == "preview"]
        for i in sub:
            if i.name in waiting:
                continue
            detail = "; ".join(x for x in (i.note, f"from {i.source}" if i.source else "") if x)
            lines.append(f"  {i.status:<8} {i.name}" + (f"  ({detail})" if detail else ""))
        if waiting:
            lines.append(f"  preview  {', '.join(waiting)}")
    for name, err in (failures or {}).items():
        lines.append(f"warning: could not read the {name} input, so it stays a preview: {err}")
    return "\n".join(lines)


def run(results: str | Path, paper: str | Path, *, dry_run: bool = False, redraw_previews: bool = False,
        main_condition: str = "auto", baseline: str = "lm", flow_areas: str = "auto", strict: bool = False,
        verbose: bool = True, **override) -> list[Item]:
    say = print if verbose else (lambda *a, **k: None)
    results, paper = Path(results), Path(paper)
    src = discover(results, **override)
    say("inputs:")
    for line in src.describe():
        say(line)
    b = build(src, main_condition=main_condition, baseline=baseline, flow_areas=flow_areas, strict=strict)
    if dry_run:
        items = [Item(n, "figure", "withheld", "", b.withheld[n]) if n in b.withheld else
                 Item(n, "figure", "real" if n in b.figures or n in b.figure_files else "preview",
                      (b.figures.get(n) or b.figure_files.get(n) or (0, ""))[1]) for n in FIGURES]
        items += [Item(n, "table", "real" if b.tables[n][2] else "preview", b.tables[n][1]) for n in TABLES]
        items += [Item(n, "number", "real" if n in b.macros else "preview", b.macros.get(n, ("", ""))[1],
                       b.macros.get(n, ("", ""))[0]) for n in b.macro_names]
        items += [Item(d, "extra", "real", s, "not used by the text yet") for d, (_, s) in b.copies.items()]
        _close()
        say("dry run, nothing written:")
    else:
        drawn = write_previews(paper, redraw=redraw_previews)
        if drawn:
            say(f"previews redrawn: {', '.join(drawn)}")
        items = write(b, paper, stamp=_dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    say(format_status(items, b.failures))
    if not dry_run:
        say(f"wrote {paper / 'figures'}; rebuild the PDF with `make -C {paper}`")
    return items


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="markov-lean paper", description=__doc__.splitlines()[0])
    p.add_argument("--results", default=str(ROOT / "results"), help="folder holding the run outputs")
    p.add_argument("--paper", default=str(ROOT / "paper"), help="paper folder (figures go to <paper>/figures)")
    for name in INPUTS:
        p.add_argument(f"--{name}", default=None, help=f"use this {name} folder instead of searching --results")
    p.add_argument("--main-condition", default="auto",
                   help="search condition reported as the area prior (auto: full, else area_l<lambda> near 0.3)")
    p.add_argument("--baseline", default="lm", help="search condition reported as the LM prior alone")
    p.add_argument("--flow-areas", choices=["auto", "judge", "macrostate"], default="auto",
                   help="areas in the flow figure: judge MSC codes when labelled (auto), or macrostates")
    p.add_argument("--redraw-previews", action="store_true", help="redraw every synthetic preview figure")
    p.add_argument("--dry-run", action="store_true", help="say what would be real, write nothing")
    p.add_argument("--strict", action="store_true", help="stop on an input that fails to load")
    a = p.parse_args(argv)
    override = {k: getattr(a, k) for k in INPUTS}
    run(a.results, a.paper, dry_run=a.dry_run, redraw_previews=a.redraw_previews, main_condition=a.main_condition,
        baseline=a.baseline, flow_areas=a.flow_areas, strict=a.strict, **override)
    return 0


if __name__ == "__main__":
    sys.exit(main())
