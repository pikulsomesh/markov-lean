def _build_significance(src: Sources, b: Build, area_cells: dict) -> None:
    """Intervals for the macro and folder rows when the robustness table has none, and the shuffle nulls."""
    if src.significance is None or not (src.significance / "significance.json").exists():
        return
    path = src.significance / "significance.json"
    rel = _rel(path, src.results.parent)
    rep = _read_json(path)
    parts = rep.get("partitions") or {}
    for key, name in (("macro", "msm"), ("folder", "folder")):
        part = parts.get(name) or {}
        cell = area_cells.get(key, {})
        if cell.get("_from") == "robustness":  # same steps as the other groupings, with its own intervals
            continue
        for k in ("nmi", "ari"):
            v = (part.get(k) or {}).get("value")
            lo, hi = (list((part.get(k) or {}).get("ci95") or []) + [None, None])[:2]
            if _finite(v):
                cell[k] = tex_ci(v, lo, hi)
        if cell:
            area_cells[key] = cell
        if key == "macro" and "resMacroNMILo" not in b.macros and "nmi" in part:
            lo, hi = (list(part["nmi"].get("ci95") or []) + [None, None])[:2]
            if _finite(lo) and _finite(hi):
                b.macros["resMacroNMILo"] = (tex_num(lo), rel)
                b.macros["resMacroNMIHi"] = (tex_num(hi), rel)
    nulls = (rep.get("shuffle_nulls") or {}).get("msm") or {}
    w = nulls.get("within_proof") or {}
    if _finite(w.get("null_mean")):
        area_cells["null_within"] = {"nmi": tex_num(w["null_mean"])}
        b.macros["resNullWithinNMI"] = (tex_num(w["null_mean"]), rel)
    if _finite(w.get("p")):
        b.macros["resNullWithinP"] = (tex_num(w["p"], 3), rel)
    g = nulls.get("global") or {}  # the same null as the robustness row shuffle; used only when that is missing
    if "null_row" not in area_cells and _finite(g.get("null_mean")):
        area_cells["null_row"] = {"nmi": tex_num(g["null_mean"])}
        b.macros.setdefault("resNullRowNMI", (tex_num(g["null_mean"]), rel))
        if _finite(g.get("p")):
            b.macros.setdefault("resNullRowP", (tex_num(g["p"], 3), rel))


