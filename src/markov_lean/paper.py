# --------------------------------------------------------------------------- formatting


def tex_int(n) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def tex_num(x, digits: int = 2) -> str:
    if not _finite(x):
        return r"\tbd"
    s = f"{float(x):.{digits}f}"
    if s.startswith("-") and float(s) == 0:  # -0.001 prints as 0.00, not as a negative zero
        s = s[1:]
    return f"$-${s[1:]}" if s.startswith("-") else s


def tex_signed(x, digits: int = 1, unit: str = "points") -> str:
    if not _finite(x):
        return r"\tbd"
    return f"${float(x):+.{digits}f}$~{unit}"


def tex_escape(s: str) -> str:
    return re.sub(r"([_%&#$])", r"\\\1", str(s))


