def tex_ci(x, lo=None, hi=None, digits: int = 2) -> str:
    """``x`` with its interval in small type under it (so table 2 fits one column), or ``\\tbd`` when
    ``x`` is missing."""
    if not _finite(x):
        return r"\tbd"
    v = tex_num(x, digits)
    if _finite(lo) and _finite(hi):
        v = (rf"\begin{{tabular}}[t]{{@{{}}c@{{}}}}{v}\\[-1pt]"
             rf"{{\scriptsize[{tex_num(lo, digits)}, {tex_num(hi, digits)}]}}\end{{tabular}}")
    return v


