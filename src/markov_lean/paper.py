def table_data_tex(rows: dict[str, tuple[str, str]]) -> str:
    """Table 1 (``tab:data``).  ``rows`` maps a source name to its (proofs, steps) cells."""
    def cell(name, i, default=r"\tbd"):
        return rows.get(name, (default, default))[i]

    lines = [
        r"\begin{tabular}{lrrl}",
        r"  \toprule",
        r"  Source & Proofs & Steps & Use \\",
        r"  \midrule",
        f"  LeanDojo Benchmark 4 & {cell('leandojo', 0)} & {cell('leandojo', 1)} & transitions \\\\",
        f"  Lean Workbook        & {cell('workbook', 0)} & {cell('workbook', 1)} & judge validation \\\\",
        f"  Synthetic (planted)  & {cell('synthetic', 0)} & {cell('synthetic', 1)} & sanity check \\\\",
        r"  \midrule",
        r"  miniF2F (test)       & 244  & --   & search \\",
        f"  PutnamBench          & {cell('putnam', 0)} & --   & search \\\\",
        r"  \bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def table_areas_tex(cells: dict[str, tuple[str, str]], m: str = "10") -> str:
    """Table 2 (``tab:areas``).  ``cells`` maps macro/folder/random/synthetic to (NMI, ARI)."""
    def c(name):
        return cells.get(name, (r"\tbd", r"\tbd"))

    lines = [
        r"\begin{tabular}{lcc}",
        r"  \toprule",
        r"  Labeling & NMI & ARI \\",
        r"  \midrule",
        f"  Macrostates ($m = {m}$)   & {c('macro')[0]} & {c('macro')[1]} \\\\",
        f"  Mathlib folder           & {c('folder')[0]} & {c('folder')[1]} \\\\",
        f"  Random partition         & {c('random')[0]} & {c('random')[1]} \\\\",
        r"  \midrule",
        f"  Synthetic, planted areas & {c('synthetic')[0]} & {c('synthetic')[1]} \\\\",
        r"  \bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def table_search_preview_tex() -> str:
    """Table 3 (``tab:search``) before any search run: one row per condition and the benchmarks
    ``configs/search_eval.yaml`` runs, all dashes."""
    rows = [label for label, _ in CONDITION_LABELS.values()]
    lines = [r"\begin{tabular}{lcc}", r"  \toprule", r"  Prior & miniF2F & PutnamBench \\", r"  \midrule"]
    lines += [f"  {r} & \\tbd & \\tbd \\\\" for r in rows]
    lines += [r"  \bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_search_tex(table: pd.DataFrame) -> str:
    """Table 3 from the runs: one row per condition (baseline first), one column per benchmark, pass@1 in %."""
    benches = list(dict.fromkeys(table["benchmark"]))
    conds = list(dict.fromkeys(table["condition"]))
    if "lm" in conds:
        conds = ["lm"] + [c for c in conds if c != "lm"]
    known = [c for c in CONDITION_LABELS if c in conds]
    conds = known + [c for c in conds if c not in CONDITION_LABELS]
    head = " & ".join(BENCHMARK_LABELS.get(b, tex_escape(b)) for b in benches)
    lines = [r"\begin{tabular}{l" + "c" * len(benches) + "}", r"  \toprule", f"  Prior & {head} \\\\", r"  \midrule"]
    t = table.set_index(["benchmark", "condition"])
    for c in conds:
        vals = []
        for b in benches:
            v = t["pass@1"].get((b, c), np.nan) if "pass@1" in t.columns else np.nan
            vals.append(tex_num(100 * v, 1) if _finite(v) else r"\tbd")
        label = CONDITION_LABELS.get(c, (tex_escape(c), c))[0]
        lines.append(f"  {label} & " + " & ".join(vals) + r" \\")
    lines += [r"  \bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def macros_tex(values: dict[str, tuple[str, str]], stamp: str | None = None,
               names: dict[str, str] | None = None) -> str:
    """``\\newcommand`` for every name in ``MACROS``; ``values`` maps a name to (TeX value, source)."""
    lines = [HEADER + (f" on {stamp}." if stamp else " (preview: every number still waits on a run)."),
             "% Do not edit by hand; rerun the command. Missing numbers print as a red dash (\\tbd)."]
    for name, what in (names or MACROS).items():
        val, source = values.get(name, (r"\tbd", ""))
        note = f"{what}" + (f"; from {source}" if source else "")
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}  % {note}")
    return "\n".join(lines) + "\n"


