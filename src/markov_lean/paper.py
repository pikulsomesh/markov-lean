def _switch_run(folder: Path | None) -> dict | None:
    """A ``markov-lean switches`` (or ``premise-labels``) output folder: its report, files and source label."""
    if folder is None or not (folder / "switches.json").exists():
        return None
    return {"dir": folder, "rep": _read_json(folder / "switches.json")}


def _premise_coverage(folder: Path) -> float | None:
    """Share of all steps with a ``premise`` label, from the ``coverage.json`` that ``premise-labels`` writes."""
    for d in (folder, *list(folder.parents)[:3]):
        if (d / "coverage.json").exists():
            for e in _read_json(d / "coverage.json").get("by_split") or []:
                if e.get("split") == "all" and e.get("source") == "premise":
                    return e.get("share_labelled")
            return None
    return None


def _premise_min_steps(run: dict):
    """The tactic-step cut of a premise run: ``inputs`` in newer runs, else a ``proofs_<k>plus`` folder name."""
    v = (run["rep"].get("inputs") or {}).get("min_switch_steps")
    if _finite(v):
        return int(v)
    for part in reversed(run["dir"].resolve().parts):
        m = re.fullmatch(r"proofs_(\d+)plus", part)
        if m:
            return int(m.group(1))
        if part == "all_proofs":
            return 1
    return None


def _dwell(run: dict, sources: list[str]) -> pd.DataFrame | None:
    p = run["dir"] / "dwell.csv"
    if not p.exists():
        return None
    d = pd.read_csv(p)
    return d[d["source"].isin(sources)]


def _build_switches(src: Sources, b: Build) -> None:
    """Table, figure and headline numbers of ``markov-lean switches``, plus the premise rows of ``premise-labels``.

    Judge and macrostate rows come from the switches run and the ``premise`` rows from the premise run; a source
    with no run stays a block of red dashes, so the table always has the same rows.
    """
    main, prem = _switch_run(src.switches), _switch_run(src.premise)
    if main is None and prem is None:
        return
    base = src.results.parent
    for r in (main, prem):
        if r is not None:
            r["rel"] = _rel(r["dir"], base)
            r["results"] = r["rep"].get("sources") or {}
    if prem is not None and "premise" not in (prem["rep"].get("headline") or {}):
        b.failures["premise"] = f"{prem['rel']}/switches.json has no `premise` source"
        prem = None

    # numbers: each source from its own run (a premise source in the switches run is used only without a premise run)
    heads: dict[str, tuple[dict, str]] = {}
    if main is not None:
        for s, h in (main["rep"].get("headline") or {}).items():
            heads[s] = (h, main["rel"])
    if prem is not None:
        heads["premise"] = (prem["rep"]["headline"]["premise"], prem["rel"])
        cov = _premise_coverage(prem["dir"])
        if _finite(cov):
            b.macros["resSwitchPremiseCoverage"] = (switch_macro_value(cov, "pct"), prem["rel"])
        k = _premise_min_steps(prem)
        if k is not None:
            b.macros["resSwitchPremiseMinSteps"] = (tex_int(k), prem["rel"])
    for s, infix in SWITCH_SOURCES.items():
        if s not in heads:
            continue
        h, rel = heads[s]
        for suffix, key, fmt, _ in SWITCH_MACROS:
            v = _headline_value(h, key)
            if _finite(v):
                b.macros[f"resSwitch{infix}{suffix}"] = (switch_macro_value(v, fmt), rel)

    # table
    real: dict[str, dict] = dict(main["results"]) if main is not None else {}
    if prem is not None and "premise" in prem["results"]:
        real["premise"] = prem["results"]["premise"]
    rels = ", ".join(r["rel"] for r in (main, prem) if r is not None)
    if main is not None and not main["results"] and (main["dir"] / "table_switches.tex").exists():
        # an older run kept only its table: copy it as it is (premise rows cannot be added to it)
        b.tables["table_switches"] = ((main["dir"] / "table_switches.tex").read_text(), main["rel"], True)
    else:
        rows: list[tuple[str, dict | None]] = []
        for s in SWITCH_SOURCES:
            if s in real:
                rows.append((s, real[s]))
            elif s == "judge" and "true_area" in real:  # synthetic runs: planted areas in the judge's place
                rows.append(("true_area", real["true_area"]))
            else:
                rows.append((s, None))
        rows += [(s, r) for s, r in real.items() if s not in {x for x, _ in rows}]
        if any(r is not None for _, r in rows):
            b.tables["table_switches"] = (table_switches_tex(rows), rels, True)

    # figure: redrawn here (at the paper's size, with any premise rows) whenever the runs kept their results and
    # dwell tables; else the switches run's own figure, copied as it is
    shown = [s for s in (main["rep"].get("headline") or {}) if s in SWITCH_SOURCES] if main is not None else []
    main_fig = main["dir"] / "switches.pdf" if main is not None else None
    from . import switches as S

    srcs = [s for s in ("judge", "true_area", "macrostate") if main is not None and s in main["results"]]
    res = {s: main["results"][s] for s in srcs}
    dws = [_dwell(main, srcs)] if srcs else []
    if prem is not None and "premise" in prem["results"]:
        res["premise"] = prem["results"]["premise"]
        dws.insert(0, _dwell(prem, ["premise"]))
    # an older switches run with a figure but no results cannot be redrawn: keep its own figure then
    legacy = main is not None and not main["results"] and main_fig.exists()
    if res and not legacy and all(d is not None for d in dws):
        b.figures["switches"] = (S.draw(res, pd.concat(dws, ignore_index=True)), rels, ", ".join(res))
        return
    if main_fig is not None and main_fig.exists():
        b.figure_files["switches"] = (main_fig, main["rel"], ", ".join(shown) if shown else "")


def _search_budget(df: pd.DataFrame, col: str) -> str | None:
    """The one budget every run used, or None when runs differ or do not say."""
    v = pd.to_numeric(df[col], errors="coerce").dropna().unique() if col in df.columns else []
    return tex_int(round(float(v[0]))) if len(v) == 1 else None


def _statement_error_split(sub: pd.DataFrame) -> tuple[list[str], list[str]]:
    """Problems of one benchmark with a statement error in every condition they ran, and in some but not all.

    A ``statement error`` is any failure to set up the theorem: the statement not elaborating, but also a
    Lean timeout or a REPL restart at that moment, which can hit one condition and not another.
    """
    from .search_report import _statement_error

    se = sub.assign(_se=_statement_error(sub)).groupby(["proof_id", "condition"], sort=False)["_se"].any()
    by_problem = se.groupby(level="proof_id", sort=False).agg(["all", "any"])
    every = by_problem.index[by_problem["all"]].tolist()
    some = by_problem.index[by_problem["any"] & ~by_problem["all"]].tolist()
    return every, some


def _build_search(src: Sources, b: Build, data_rows: dict, main_condition: str, baseline: str,
                  n_boot: int) -> bool:
    if src.search is None:
        return False
    report = src.search / "report"  # `markov-lean search-report --runs <search>` writes here by default
    if report.is_dir():
        for f in sorted(list(report.glob("*.tex")) + list(report.glob("*.pdf"))):
            stem = f.stem[4:] if f.stem.startswith("fig_") else f.stem
            b.copies[f"search_{stem}{f.suffix}"] = (f, _rel(f, src.results.parent))
    df = search_frame(src.search)
    if df.empty:
        return False
    from . import figures as fg
    from .search_report import _statement_error, paired_compare

    rel = _rel(src.search, src.results.parent)
    conds = list(dict.fromkeys(df["condition"]))
    area = area_condition(conds, main_condition)
    control = random_control(conds, area)
    table = search_pass_table(df, n_boot=n_boot)
    b.tables["table_search"] = (table_search_tex(table), rel, bool(len(table)))
    if len(table):
        b.macros["resSearchSeeds"] = (str(int(table["n_seeds"].min())), rel)
    if area is not None:
        b.macros["resSearchCondition"] = (r"\texttt{" + tex_escape(area) + "}", rel)
    for col, name in (("max_expansions", "resSearchExpansions"), ("wall_time", "resSearchWallTime")):
        val = _search_budget(df, col)
        if val is not None:
            b.macros[name] = (val, rel)
    paired = paired_compare(df, baseline=baseline, n_boot=n_boot, seed=0)
    pair = paired.set_index(["benchmark", "condition"])
    t = table.set_index(["benchmark", "condition"])
    for bench in dict.fromkeys(table["benchmark"]):
        sfx = macro_suffix(bench)
        for k, v in search_macro_names(bench, sfx).items():
            b.macro_names.setdefault(k, v)  # a benchmark the text does not know yet
        sub = df[df["benchmark"] == bench]
        b.macros[f"resSearchProblems{sfx}"] = (tex_int(sub["proof_id"].nunique()), rel)
        every, some = _statement_error_split(sub)
        b.macros[f"resSearchStatementErrors{sfx}"] = (tex_int(len(every)), rel)
        b.macros[f"resSearchStatementErrorsSome{sfx}"] = (tex_int(len(some)), rel)
        # Base, area and gain on the problems both conditions ran, so a partial run compares like with like;
        # with no area run yet, the base rate is the LM condition's own pass@1.
        r = pair.loc[(bench, area)] if area and (bench, area) in pair.index else None
        if r is not None and r["n_common"] > 0:
            base, val = r["rate_base"], r["rate_cond"]
            b.macros[f"resSearchShared{sfx}"] = (tex_int(r["n_common"]), rel)
        else:
            base = t["pass@1"].get((bench, baseline), np.nan) if "pass@1" in t.columns else np.nan
            val = np.nan
        if _finite(base):
            b.macros[f"resSearchBase{sfx}"] = (tex_num(100 * base, 1), rel)
        if _finite(val):
            b.macros[f"resSearchArea{sfx}"] = (tex_num(100 * val, 1), rel)
        if _finite(base) and _finite(val):
            b.macros[f"resSearchGain{sfx}"] = (tex_signed(100 * (val - base)), rel)
        if r is not None and _finite(r["diff_lo"]) and _finite(r["diff_hi"]):
            b.macros[f"resSearchGainLo{sfx}"] = (tex_signed(100 * r["diff_lo"], unit="").rstrip("~"), rel)
            b.macros[f"resSearchGainHi{sfx}"] = (tex_signed(100 * r["diff_hi"], unit="").rstrip("~"), rel)
        if area and {baseline, area} <= set(sub["condition"]):
            two = sub[sub["condition"].isin([baseline, area])]
            bad = set(two.loc[_statement_error(two), "proof_id"])
            clean = paired_compare(two[~two["proof_id"].isin(bad)], baseline=baseline, n_boot=n_boot, seed=0)
            if len(clean) and _finite(clean["diff"].iloc[0]):
                r = clean.iloc[0]
                b.macros[f"resSearchGainElab{sfx}"] = (tex_signed(100 * r["diff"]), rel)
                if _finite(r["diff_lo"]) and _finite(r["diff_hi"]):
                    b.macros[f"resSearchGainElabLo{sfx}"] = (tex_signed(100 * r["diff_lo"], unit="").rstrip("~"), rel)
                    b.macros[f"resSearchGainElabHi{sfx}"] = (tex_signed(100 * r["diff_hi"], unit="").rstrip("~"), rel)
        if control and (bench, control) in pair.index and _finite(pair.loc[(bench, control), "diff"]):
            b.macros[f"resSearchRandomGain{sfx}"] = (tex_signed(100 * pair.loc[(bench, control), "diff"]), rel)
    if "putnam" not in data_rows and "putnam" in set(df["benchmark"]):
        data_rows["putnam"] = (tex_int(df.loc[df["benchmark"] == "putnam", "proof_id"].nunique()), "--")

    if area is None:  # one bar says nothing: the figure waits for the area-prior run
        want = "an area-prior condition (`full` or `area_l<lambda>`)" if main_condition == "auto" \
            else f"`{main_condition}`"
        b.withheld["search_ablation"] = f"no {want} run yet; the paper leaves the figure out"
        return True
    if baseline not in conds:
        b.withheld["search_ablation"] = f"no `{baseline}` (LM prior) run to compare the area prior with"
        return True
    order = [baseline, area] + ([control] if control else [])
    order += [c for c in CONDITION_LABELS if c in conds and c not in order]
    order += [c for c in conds if c not in order]
    label = {c: CONDITION_LABELS.get(c, (c, c))[1] for c in order}
    if area != "full":  # the dynamics term alone stands in for the area prior: say which weight
        label[area] = CONDITION_LABELS.get(area, (area, area))[1].replace("area,", "area prior,")
    rates = table[table["condition"].isin(order)].copy()
    for col in ("pass@1", "pass@1_lo", "pass@1_hi"):  # pass_table drops interval columns it could not fill
        if col not in rates.columns:
            rates[col] = np.nan
    rates = rates.assign(method=rates["condition"].map(label), group=rates["benchmark"].map(
        lambda x: BENCHMARK_LABELS.get(x, x)), rate=100 * rates["pass@1"], lo=100 * rates["pass@1_lo"],
        hi=100 * rates["pass@1_hi"])
    rates = rates.iloc[np.argsort(rates["condition"].map(order.index).to_numpy(), kind="stable")]
    diffs = paired[paired["condition"].isin(order)].copy()
    diffs = diffs.assign(method=diffs["condition"].map(label), group=diffs["benchmark"].map(
        lambda x: BENCHMARK_LABELS.get(x, x)), diff=100 * diffs["diff"], lo=100 * diffs["diff_lo"],
        hi=100 * diffs["diff_hi"])
    fig = fg.search_paired(rates, diffs, baseline=label[baseline], group_col="group")
    b.figures["search_ablation"] = (fig, rel, f"{len(order)} conditions, area prior `{area}`")
    return True


def _build_accuracy(src: Sources, b: Build) -> None:
    """Gold-set sizes and each API judge's accuracy, from ``markov-lean judge-accuracy``."""
    if src.accuracy is None or not (src.accuracy / "judge_accuracy.json").exists():
        return
    path = src.accuracy / "judge_accuracy.json"
    rel = _rel(path, src.results.parent)
    rep = _read_json(path)
    status = (rep.get("gold") or {}).get("status") or {}
    strict, family = status.get("strict"), status.get("family")
    if _finite(strict):
        b.macros["resGoldStrict"] = (tex_int(strict), rel)
    if _finite(family):
        b.macros["resGoldFamily"] = (tex_int(family), rel)
    if _finite(strict) and _finite(family):
        b.macros["resGoldProblems"] = (tex_int(strict + family), rel)
    for name, r in (rep.get("judges") or {}).items():
        infix = next((v for k, v in GOLD_JUDGES.items() if k in str(name).lower()), None)
        if infix is None:
            continue
        st, fa = r.get("strict") or {}, r.get("family") or {}
        if _finite(st.get("accuracy")):
            b.macros[f"resGoldAcc{infix}"] = (switch_macro_value(st["accuracy"], "pct"), rel)
        lo, hi = (list(st.get("accuracy_ci") or []) + [None, None])[:2]
        if _finite(lo) and _finite(hi):
            b.macros[f"resGoldAcc{infix}Lo"] = (switch_macro_value(lo, "pct"), rel)
            b.macros[f"resGoldAcc{infix}Hi"] = (switch_macro_value(hi, "pct"), rel)
        if _finite(fa.get("accuracy")):
            b.macros[f"resGoldFamAcc{infix}"] = (switch_macro_value(fa["accuracy"], "pct"), rel)
        if _finite(st.get("majority_baseline_accuracy")):
            b.macros.setdefault("resGoldMajority", (switch_macro_value(st["majority_baseline_accuracy"], "pct"), rel))


def build(src: Sources, *, main_condition: str = "auto", baseline: str = "lm", flow_areas: str = "auto",
          n_boot: int = 200, strict: bool = False) -> Build:
    """Make every figure, table and number the inputs allow, without writing anything."""
    b = Build()
    data_rows: dict[str, tuple[str, str]] = {}
    area_cells: dict[str, tuple[str, str]] = {}

    def guarded(name: str, fn: Callable, *args) -> Any:
        try:
            return fn(*args)
        except Exception as exc:  # one broken input must not stop the rest of the paper
            if strict:
                raise
            b.failures[name] = f"{type(exc).__name__}: {exc}"
            return None

    guarded("msm", _build_msm, src, b)
    guarded("pilot", _build_pilot, src, b, data_rows, area_cells, flow_areas)
    guarded("full", _build_full, src, b, data_rows)
    guarded("synthetic", _build_synthetic, src, b, data_rows, area_cells)
    guarded("robustness", _build_robustness, src, b, area_cells)
    guarded("significance", _build_significance, src, b, area_cells)
    guarded("bridges", _build_bridges, src, b)
    guarded("switches", _build_switches, src, b)
    guarded("accuracy", _build_accuracy, src, b)
    guarded("search", _build_search, src, b, data_rows, main_condition, baseline, n_boot)

    m = b.macros.get("resNumMacrostates", ("10", ""))[0]
    srcs = ", ".join(x for x in (_rel(src.full, src.results.parent), _rel(src.pilot, src.results.parent),
                                 _rel(src.synthetic, src.results.parent)) if x)
    b.tables["table_data"] = (table_data_tex(data_rows), srcs, bool(data_rows))
    area_srcs = ", ".join(x for x in (_rel(src.pilot, src.results.parent), _rel(src.robustness, src.results.parent),
                                      _rel(src.significance, src.results.parent),
                                      _rel(src.synthetic, src.results.parent)) if x)
    b.tables["table_areas"] = (table_areas_tex(area_cells, m), area_srcs, bool(area_cells))
    if "table_search" not in b.tables:
        b.tables["table_search"] = (table_search_preview_tex(), "", False)
    if "table_switches" not in b.tables:
        b.tables["table_switches"] = (table_switches_preview_tex(), "", False)
    return b


