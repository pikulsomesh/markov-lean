def _finite(x) -> bool:
    try:
        return x is not None and bool(np.isfinite(float(x)))
    except (TypeError, ValueError):
        return False


def pilot_report(src: Sources) -> dict | None:
    if src.pilot and (src.pilot / "pilot_report.json").exists():
        return _read_json(src.pilot / "pilot_report.json")
    return None


def labelled_steps(pilot_dir: Path, report: dict | None = None) -> pd.DataFrame | None:
    """The pilot's assignments joined to the judges' consensus MSC code, whole-proof labels broadcast.

    The same rows ``markov-lean pilot`` scores at gate 1.  ``None`` when the
    folder has no labels or assignments yet.
    """
    a_path, l_path = pilot_dir / "msm" / "assignments.parquet", pilot_dir / "judge" / "labels.parquet"
    if not (a_path.exists() and l_path.exists()):
        return None
    from .pilot import consensus_labels

    a = pd.read_parquet(a_path)
    a["proof_id"] = a["proof_id"].astype(str)
    a["step"] = a["step"].astype("int64")
    labels = pd.read_parquet(l_path)
    judges = ((report or {}).get("judge_agreement") or {}).get("judges")
    present = set(labels["judge"].astype(str))
    judges = [j for j in (judges or []) if j != "consensus" and j in present]
    judges = judges if len(judges) >= 2 else None  # else consensus_labels picks what the table holds
    cons, _ = consensus_labels(labels, judges)
    lab = cons[KEY + ["msc"]].copy()
    lab["proof_id"] = lab["proof_id"].astype(str)
    lab["step"] = lab["step"].astype("int64")
    whole = lab[lab["step"] == -1]
    if len(whole):
        expanded = a[KEY].merge(whole[["proof_id", "msc"]], on="proof_id")
        lab = pd.concat([lab[lab["step"] != -1], expanded]).drop_duplicates(KEY, keep="first")
    out = a.merge(lab, on=KEY, how="inner")
    out = out[out["macrostate"] >= 0]
    return out if len(out) else None


def consecutive_flows(df: pd.DataFrame, area_col: str) -> pd.DataFrame:
    """Moves from step t to t + 1 of the same proof whose areas differ (steps must both be present)."""
    d = df[KEY + [area_col]].dropna().sort_values(KEY)
    nxt = d.groupby("proof_id", sort=False).shift(-1)
    ok = (nxt["step"] == d["step"] + 1) & (nxt[area_col].astype(str) != d[area_col].astype(str))
    pairs = pd.DataFrame({"from_area": d.loc[ok, area_col].to_numpy(), "to_area": nxt.loc[ok, area_col].to_numpy()})
    if pairs.empty:
        return pd.DataFrame({"from_area": [], "to_area": [], "count": []}).astype({"count": int})
    out = pairs.groupby(["from_area", "to_area"]).size().rename("count").reset_index()
    return out.sort_values("count", ascending=False, kind="stable").reset_index(drop=True)


