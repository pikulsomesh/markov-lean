def _build_msm(src: Sources, b: Build) -> None:
    if src.msm is None or not (src.msm / "msm_report.json").exists():
        return
    from . import figures as fg

    rel = _rel(src.msm, src.results.parent)
    rep = _read_json(src.msm / "msm_report.json")
    m = int(rep.get("n_macrostates") or 0)
    labels = [f"M{k + 1}" for k in range(m)] if m else None
    b.macros["resLag"] = (str(int(rep["lag"])), rel)
    if m:
        b.macros["resNumMacrostates"] = (str(m), rel)
    if rep.get("n_microstates"):
        b.macros["resNumMicrostates"] = (str(int(rep["n_microstates"])), rel)
    ts = rep.get("timescales_steps") or []
    if ts and _finite(ts[0]):
        b.macros["resSlowestTimescale"] = (tex_num(ts[0], 1), rel)
    checks = rep.get("checks") or {}
    if checks:
        b.macros["resChecksFailed"] = (str(sum(not c.get("passed") for c in checks.values())), rel)

    its_p = src.msm / "implied_timescales.csv"
    if its_p.exists():
        its = pd.read_csv(its_p)
        if len(its):
            n_show = max(1, min((m - 1) if m > 1 else 3, 6))
            keep = sorted(its["index"].unique())[:n_show]
            piv = its[its["index"].isin(keep)].pivot(index="lag", columns="index", values="timescale").sort_index()
            b.figures["implied_timescales"] = (fg.implied_timescales(piv.index.to_numpy(), piv.to_numpy()), rel,
                                               f"{len(keep)} slowest processes")
    ct_p = src.msm / "coarse_T.npy"
    if ct_p.exists():
        T = np.load(ct_p)
        names = labels if labels and len(labels) == T.shape[0] else [f"M{k + 1}" for k in range(T.shape[0])]
        b.figures["transition_matrix"] = (fg.transition_heatmap(T, names, check_stochastic=False), rel, "")
    ck_p = src.msm / "ck_test.csv"
    if ck_p.exists():
        ck = pd.read_csv(ck_p)
        if len(ck):
            lags = sorted(ck["lag"].unique())
            k = int(max(ck["from_set"].max(), ck["to_set"].max())) + 1
            pred = np.zeros((len(lags), k, k))
            est = np.zeros_like(pred)
            for li, L in enumerate(lags):
                sub = ck[ck["lag"] == L]
                i, j = sub["from_set"].to_numpy(int), sub["to_set"].to_numpy(int)
                pred[li, i, j] = sub["predicted"].to_numpy()
                est[li, i, j] = sub["estimated"].to_numpy()
            b.figures["chapman_kolmogorov"] = (
                fg.chapman_kolmogorov(lags, pred, est, labels=[f"M{x + 1}" for x in range(k)]), rel, "")


def _build_pilot(src: Sources, b: Build, data_rows: dict, area_cells: dict, flow_areas: str) -> None:
    rep = pilot_report(src)
    if rep is None:
        return
    rel = _rel(src.pilot / "pilot_report.json", src.results.parent)
    d = rep.get("data") or {}
    if "n_proofs" in d and "leandojo" not in data_rows:
        data_rows["leandojo"] = (tex_int(d["n_proofs"]), tex_int(d["n_steps"]))
        b.macros.setdefault("resNumProofs", (tex_int(d["n_proofs"]), rel))
        b.macros.setdefault("resNumSteps", (tex_int(d["n_steps"]), rel))
    ev = rep.get("eval")
    if ev:
        mac, fol = ev.get("macrostates") or {}, ev.get("folder_baseline") or {}
        area_cells["macro"] = (tex_num(mac.get("nmi")), tex_num(mac.get("ari")))
        area_cells["folder"] = (tex_num(fol.get("nmi")), tex_num(fol.get("ari")))
        b.macros["resMacroNMI"] = (tex_num(mac.get("nmi")), rel)
        b.macros["resMacroARI"] = (tex_num(mac.get("ari")), rel)
        b.macros["resFolderNMI"] = (tex_num(fol.get("nmi")), rel)
        b.macros["resFolderARI"] = (tex_num(fol.get("ari")), rel)
        if ev.get("n_labelled_steps"):
            b.macros["resNumLabelledSteps"] = (tex_int(ev["n_labelled_steps"]), rel)
        g = ev.get("gate1") or {}
        if "passed" in g:
            b.macros["resGateOne"] = ("passed" if g["passed"] else "failed", rel)
    agree = (rep.get("judge_agreement") or {}).get("step") or {}
    if _finite(agree.get("kappa")):
        b.macros["resJudgeKappa"] = (tex_num(agree["kappa"]), rel)
    if _finite(agree.get("agreement")):
        b.macros["resJudgeAgreement"] = (tex_num(100 * agree["agreement"], 0), rel)

    lab = labelled_steps(src.pilot, rep)
    if lab is not None:
        from . import figures as fg

        lrel = _rel(src.pilot / "judge" / "labels.parquet", src.results.parent)
        clusters = lab["macrostate"].map(lambda k: f"M{int(k) + 1}")
        fig = fg.judge_cluster_confusion(clusters.to_numpy(), lab["msc"].astype(str).to_numpy())
        b.figures["judge_confusion"] = (fig, lrel, f"NMI {getattr(fig, 'nmi', float('nan')):.3f}")
        if flow_areas in ("auto", "judge"):
            _flow(b, lab, "msc", lrel, "judge MSC codes")
    if "area_flow" not in b.figures and flow_areas in ("auto", "macrostate") and src.msm is not None:
        a_p = src.msm / "assignments.parquet"
        if a_p.exists():
            a = pd.read_parquet(a_p)
            a = a[a["macrostate"] >= 0].assign(area=lambda x: x["macrostate"].map(lambda k: f"M{int(k) + 1}"))
            _flow(b, a, "area", _rel(a_p, src.results.parent), "macrostates (no judge labels yet)")


def _flow(b: Build, df: pd.DataFrame, col: str, source: str, what: str, top: int = 10) -> None:
    from . import figures as fg

    flows = consecutive_flows(df, col)
    if flows.empty:
        return
    fig = fg.area_flow(flows, top=top)
    b.figures["area_flow"] = (fig, source, f"areas are {what}")
    b.macros["resFlowsShown"] = (str(int(fig.flows_shown)), source)
    b.macros["resFlowCoverage"] = (tex_num(100 * fig.moves_shown / max(fig.moves_total, 1), 0), source)


def _build_full(src: Sources, b: Build, data_rows: dict) -> None:
    if src.full is None or not (src.full / "full_report.json").exists():
        return
    rep = _read_json(src.full / "full_report.json")
    rel = _rel(src.full / "full_report.json", src.results.parent)
    d = rep.get("data") or {}
    if "n_proofs" in d:  # the full fit supersedes the pilot's sample in the data table
        data_rows["leandojo"] = (tex_int(d["n_proofs"]), tex_int(d["n_steps"]))
        b.macros["resNumProofs"] = (tex_int(d["n_proofs"]), rel)
        b.macros["resNumSteps"] = (tex_int(d["n_steps"]), rel)
    summ = src.full / "project" / "summary.parquet"
    if summ.exists():
        s = pd.read_parquet(summ)
        name_col = "dataset" if "dataset" in s.columns else s.columns[0]
        s = s.set_index(name_col)
        for ds, row in (("workbook", "workbook"), ("putnam", "putnam")):
            if ds in s.index:
                data_rows[row] = (tex_int(s.loc[ds, "n_proofs"]), tex_int(s.loc[ds, "n_steps"]))


def _build_synthetic(src: Sources, b: Build, data_rows: dict, area_cells: dict) -> None:
    if src.synthetic is None or not (src.synthetic / "pilot_report.json").exists():
        return
    rep = _read_json(src.synthetic / "pilot_report.json")
    rel = _rel(src.synthetic / "pilot_report.json", src.results.parent)
    d = rep.get("data") or {}
    if "n_proofs" in d:
        data_rows["synthetic"] = (tex_int(d["n_proofs"]), tex_int(d["n_steps"]))
    mac = (rep.get("eval") or {}).get("macrostates") or {}
    if mac:
        area_cells["synthetic"] = (tex_num(mac.get("nmi")), tex_num(mac.get("ari")))
        b.macros["resSyntheticNMI"] = (tex_num(mac.get("nmi")), rel)


def _build_robustness(src: Sources, b: Build, area_cells: dict) -> None:
    if src.robustness is None:
        return
    base = src.robustness / "baselines.csv"
    if base.exists():
        t = pd.read_csv(base).set_index("grouping")
        if "random" in t.index:
            rel = _rel(base, src.results.parent)
            area_cells["random"] = (tex_num(t.loc["random", "nmi"]), tex_num(t.loc["random", "ari"]))
            b.macros["resRandomNMI"] = (tex_num(t.loc["random", "nmi"]), rel)
            b.macros["resRandomARI"] = (tex_num(t.loc["random", "ari"]), rel)
    rj = src.robustness / "robustness.json"
    if rj.exists():
        ceil = _read_json(rj).get("judge_ceiling") or {}
        rel = _rel(rj, src.results.parent)
        if _finite(ceil.get("nmi")):
            b.macros["resJudgeCeilingNMI"] = (tex_num(ceil["nmi"]), rel)
        if _finite(ceil.get("kappa")):
            b.macros.setdefault("resJudgeKappa", (tex_num(ceil["kappa"]), rel))
        if _finite(ceil.get("raw_agreement")):
            b.macros.setdefault("resJudgeAgreement", (tex_num(100 * ceil["raw_agreement"], 0), rel))
    figs = src.robustness / "figures"
    if figs.is_dir():
        for p in sorted(figs.glob("*.pdf")):
            b.copies[f"robustness_{p.stem}.pdf"] = (p, _rel(p, src.results.parent))


def _build_bridges(src: Sources, b: Build) -> None:
    if src.bridges is not None and (src.bridges / "bridges.pdf").exists():
        p = src.bridges / "bridges.pdf"
        b.copies["bridges.pdf"] = (p, _rel(p, src.results.parent))


def _build_search(src: Sources, b: Build, data_rows: dict, main_condition: str, baseline: str,
                  n_boot: int) -> bool:
    if src.search is None:
        return False
    report = src.search / "report"  # `markov-lean search-report --runs <search>` writes here by default
    if report.is_dir():
        for f in sorted(list(report.glob("*.tex")) + list(report.glob("*.pdf"))):
            stem = f.stem[4:] if f.stem.startswith("fig_") else f.stem
            b.copies[f"search_{stem}{f.suffix}"] = (f, _rel(f, src.results.parent))
    df = search_frame(src.search)
    if df.empty:
        return False
    from . import figures as fg

    rel = _rel(src.search, src.results.parent)
    table = search_pass_table(df, n_boot=n_boot)
    b.tables["table_search"] = (table_search_tex(table), rel, bool(len(table)))
    if len(table):
        b.macros["resSearchSeeds"] = (str(int(table["n_seeds"].min())), rel)
    t = table.set_index(["benchmark", "condition"])
    for bench in dict.fromkeys(table["benchmark"]):
        sfx = macro_suffix(bench)
        base = t["pass@1"].get((bench, baseline), np.nan) if "pass@1" in t.columns else np.nan
        area = t["pass@1"].get((bench, main_condition), np.nan) if "pass@1" in t.columns else np.nan
        if _finite(base):
            b.macros[f"resSearchBase{sfx}"] = (tex_num(100 * base, 1), rel)
        if _finite(area):
            b.macros[f"resSearchArea{sfx}"] = (tex_num(100 * area, 1), rel)
        if _finite(base) and _finite(area):
            b.macros[f"resSearchGain{sfx}"] = (tex_signed(100 * (area - base)), rel)
        if f"resSearchGain{sfx}" not in b.macro_names:  # a benchmark the text does not know yet
            b.macro_names[f"resSearchBase{sfx}"] = f"{bench}: problems solved (%) with the LM prior alone"
            b.macro_names[f"resSearchArea{sfx}"] = f"{bench}: problems solved (%) with the area prior"
            b.macro_names[f"resSearchGain{sfx}"] = f"{bench}: area prior minus LM prior, in points"
    if "putnam" not in data_rows and "putnam" in set(df["benchmark"]):
        data_rows["putnam"] = (tex_int(df.loc[df["benchmark"] == "putnam", "proof_id"].nunique()), "--")

    per_seed = (df.groupby(["benchmark", "condition", "seed"], sort=False)["solved"].mean() * 100).reset_index()
    conds = list(dict.fromkeys(per_seed["condition"]))
    order = ([baseline] if baseline in conds else []) + [c for c in conds if c != baseline]
    per_seed["method"] = per_seed["condition"].map(lambda c: CONDITION_LABELS.get(c, (c, c))[1])
    per_seed["benchmark"] = per_seed["benchmark"].map(lambda x: BENCHMARK_LABELS.get(x, x))
    per_seed = per_seed.iloc[np.argsort(per_seed["condition"].map(order.index).to_numpy(), kind="stable")]
    b.figures["search_ablation"] = (fg.search_ablation(per_seed, metric_col="solved", group_col="benchmark"), rel,
                                    f"{len(conds)} conditions")
    return True


def build(src: Sources, *, main_condition: str = "full", baseline: str = "lm", flow_areas: str = "auto",
          n_boot: int = 200, strict: bool = False) -> Build:
    """Make every figure, table and number the inputs allow, without writing anything."""
    b = Build()
    data_rows: dict[str, tuple[str, str]] = {}
    area_cells: dict[str, tuple[str, str]] = {}

    def guarded(name: str, fn: Callable, *args) -> Any:
        try:
            return fn(*args)
        except Exception as exc:  # one broken input must not stop the rest of the paper
            if strict:
                raise
            b.failures[name] = f"{type(exc).__name__}: {exc}"
            return None

    guarded("msm", _build_msm, src, b)
    guarded("pilot", _build_pilot, src, b, data_rows, area_cells, flow_areas)
    guarded("full", _build_full, src, b, data_rows)
    guarded("synthetic", _build_synthetic, src, b, data_rows, area_cells)
    guarded("robustness", _build_robustness, src, b, area_cells)
    guarded("bridges", _build_bridges, src, b)
    guarded("search", _build_search, src, b, data_rows, main_condition, baseline, n_boot)

    m = b.macros.get("resNumMacrostates", ("10", ""))[0]
    srcs = ", ".join(x for x in (_rel(src.full, src.results.parent), _rel(src.pilot, src.results.parent),
                                 _rel(src.synthetic, src.results.parent)) if x)
    b.tables["table_data"] = (table_data_tex(data_rows), srcs, bool(data_rows))
    b.tables["table_areas"] = (table_areas_tex(area_cells, m), srcs, bool(area_cells))
    if "table_search" not in b.tables:
        b.tables["table_search"] = (table_search_preview_tex(), "", False)
    return b


