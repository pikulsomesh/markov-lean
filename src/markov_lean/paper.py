def _build_robustness(src: Sources, b: Build, area_cells: dict) -> None:
    if src.robustness is None:
        return
    base = src.robustness / "baselines.csv"
    if base.exists():
        rel = _rel(base, src.results.parent)
        t = pd.read_csv(base).set_index("grouping")
        for g, r in t.iterrows():
            key = "macro" if g == "macrostate" else str(g)
            if key not in AREA_ROWS:
                continue
            # every grouping is scored on the same steps, so a row here replaces the pilot's own cells
            cell = {k: tex_ci(r.get(k), r.get(f"{k}_lo"), r.get(f"{k}_hi")) for k in AREA_METRICS if _finite(r.get(k))}
            if cell:
                area_cells[key] = {**cell, "_from": "robustness"}
        for g, k, name in ROBUSTNESS_MACROS:
            if g in t.index and _finite(t.loc[g].get(k)):
                b.macros[name] = (tex_num(t.loc[g, k]), rel)
        if "macrostate" in t.index and _finite(t.loc["macrostate"].get("nmi_lo")) \
                and _finite(t.loc["macrostate"].get("nmi_hi")):
            b.macros["resMacroNMILo"] = (tex_num(t.loc["macrostate", "nmi_lo"]), rel)
            b.macros["resMacroNMIHi"] = (tex_num(t.loc["macrostate", "nmi_hi"]), rel)
    rj = src.robustness / "robustness.json"
    if rj.exists():
        rep = _read_json(rj)
        ceil = rep.get("judge_ceiling") or {}
        rel = _rel(rj, src.results.parent)
        if _finite(ceil.get("nmi")):
            b.macros["resJudgeCeilingNMI"] = (tex_num(ceil["nmi"]), rel)
        if _finite(ceil.get("kappa")):
            b.macros.setdefault("resJudgeKappa", (tex_num(ceil["kappa"]), rel))
        if _finite(ceil.get("raw_agreement")):
            b.macros.setdefault("resJudgeAgreement", (tex_num(100 * ceil["raw_agreement"], 0), rel))
        null = (rep.get("baselines") or {}).get("null") or {}
        for kind, key, name in (("row", "null_row", "Row"), ("proof", "null_proof", "Proof")):
            n = null.get(kind) or {}
            cell = {k: tex_num(n[f"{k}_mean"]) for k in ("nmi", "ari") if _finite(n.get(f"{k}_mean"))}
            if cell:
                area_cells[key] = cell
            if _finite(n.get("nmi_mean")):
                b.macros[f"resNull{name}NMI"] = (tex_num(n["nmi_mean"]), rel)
            if _finite(n.get("p_nmi")):
                b.macros[f"resNull{name}P"] = (tex_num(n["p_nmi"], 3), rel)
    figs = src.robustness / "figures"
    if figs.is_dir():
        for p in sorted(figs.glob("*.pdf")):
            b.copies[f"robustness_{p.stem}.pdf"] = (p, _rel(p, src.results.parent))


