# --------------------------------------------------------------------------- bookkeeping


@dataclass
class Item:
    name: str
    kind: str
    status: str
    source: str = ""
    note: str = ""


@dataclass
class Sources:
    results: Path
    pilot: Path | None = None
    synthetic: Path | None = None
    full: Path | None = None
    msm: Path | None = None
    search: Path | None = None
    robustness: Path | None = None
    bridges: Path | None = None

    def describe(self) -> list[str]:
        out = []
        for name in ("pilot", "synthetic", "full", "msm", "search", "robustness", "bridges"):
            v = getattr(self, name)
            out.append(f"  {name:<11} {v if v is not None else '(none)'}")
        return out


@dataclass
class Build:
    """What one run of the command made, before anything is written."""
    figures: dict[str, tuple[Any, str, str]] = field(default_factory=dict)   # name -> (fig, source, note)
    tables: dict[str, tuple[str, str, bool]] = field(default_factory=dict)  # name -> (tex, source, any real)
    macros: dict[str, tuple[str, str]] = field(default_factory=dict)        # name -> (value, source)
    copies: dict[str, tuple[Path, str]] = field(default_factory=dict)       # out name -> (file, source)
    failures: dict[str, str] = field(default_factory=dict)
    macro_names: dict[str, str] = field(default_factory=lambda: dict(MACROS))  # MACROS plus new benchmarks


def _read_json(path: Path) -> dict:
    return json.loads(Path(path).read_text())


def _natural(p: Path) -> list:
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", p.name)]


def _rel(p: Path | None, base: Path) -> str:
    if p is None:
        return ""
    try:
        return str(Path(p).resolve().relative_to(base.resolve()))
    except ValueError:
        return str(p)


# --------------------------------------------------------------------------- discovery


def _pilot_reports(results: Path) -> list[tuple[Path, dict]]:
    out = []
    for rep in sorted(results.glob("*/pilot_report.json"), key=lambda p: _natural(p.parent)):
        try:
            out.append((rep.parent, _read_json(rep)))
        except (OSError, json.JSONDecodeError):
            continue
    return out


def _has_search_runs(d: Path) -> bool:
    return d.is_dir() and any(d.glob("*/*/seed*/summary.jsonl"))


def discover(results: str | Path, **override: str | Path | None) -> Sources:
    """Find every input folder under ``results``; ``override`` sets any of them by hand."""
    results = Path(results)
    src = Sources(results=results)
    reports = _pilot_reports(results) if results.is_dir() else []
    real = [(d, r) for d, r in reports if (r.get("data") or {}).get("source") != "synthetic"]
    synth = [(d, r) for d, r in reports if (r.get("data") or {}).get("source") == "synthetic"]
    if real:  # labelled pilots first, then the highest-numbered folder
        src.pilot = sorted(real, key=lambda dr: ("eval" in dr[1], _natural(dr[0])))[-1][0]
    if synth:
        src.synthetic = synth[-1][0]
    fulls = sorted(results.glob("*/full_report.json"), key=lambda p: _natural(p.parent)) if results.is_dir() else []
    if fulls:
        src.full = fulls[-1].parent
    if results.is_dir():
        if _has_search_runs(results / "search_eval"):
            src.search = results / "search_eval"
        else:
            src.search = next((d for d in sorted(results.iterdir()) if _has_search_runs(d)), None)
    for k, v in override.items():
        if v is not None:
            setattr(src, k, Path(v))
    if src.msm is None:
        for cand in ([src.full / "msm"] if src.full else []) + ([src.pilot / "msm"] if src.pilot else []):
            if (cand / "msm_report.json").exists():
                src.msm = cand
                break
    if src.robustness is None:
        cands = ([src.pilot / "robustness"] if src.pilot else []) + [results / "robustness"]
        src.robustness = next((c for c in cands if (c / "baselines.csv").exists() or (c / "robustness.json").exists()),
                              None)
    if src.bridges is None:
        cands = [results / "bridges"] + ([src.pilot / "bridges"] if src.pilot else [])
        src.bridges = next((c for c in cands if (c / "summary.json").exists() or (c / "bridges.pdf").exists()), None)
    return src


# --------------------------------------------------------------------------- loading


def _finite(x) -> bool:
    try:
        return x is not None and bool(np.isfinite(float(x)))
    except (TypeError, ValueError):
        return False


def pilot_report(src: Sources) -> dict | None:
    if src.pilot and (src.pilot / "pilot_report.json").exists():
        return _read_json(src.pilot / "pilot_report.json")
    return None


def labelled_steps(pilot_dir: Path, report: dict | None = None) -> pd.DataFrame | None:
    """The pilot's assignments joined to the judges' consensus MSC code, whole-proof labels broadcast.

    The same rows ``markov-lean pilot`` scores at gate 1.  ``None`` when the
    folder has no labels or assignments yet.
    """
    a_path, l_path = pilot_dir / "msm" / "assignments.parquet", pilot_dir / "judge" / "labels.parquet"
    if not (a_path.exists() and l_path.exists()):
        return None
    from .pilot import consensus_labels

    a = pd.read_parquet(a_path)
    a["proof_id"] = a["proof_id"].astype(str)
    a["step"] = a["step"].astype("int64")
    labels = pd.read_parquet(l_path)
    judges = ((report or {}).get("judge_agreement") or {}).get("judges")
    present = set(labels["judge"].astype(str))
    judges = [j for j in (judges or []) if j != "consensus" and j in present]
    judges = judges if len(judges) >= 2 else None  # else consensus_labels picks what the table holds
    cons, _ = consensus_labels(labels, judges)
    lab = cons[KEY + ["msc"]].copy()
    lab["proof_id"] = lab["proof_id"].astype(str)
    lab["step"] = lab["step"].astype("int64")
    whole = lab[lab["step"] == -1]
    if len(whole):
        expanded = a[KEY].merge(whole[["proof_id", "msc"]], on="proof_id")
        lab = pd.concat([lab[lab["step"] != -1], expanded]).drop_duplicates(KEY, keep="first")
    out = a.merge(lab, on=KEY, how="inner")
    out = out[out["macrostate"] >= 0]
    return out if len(out) else None


def consecutive_flows(df: pd.DataFrame, area_col: str) -> pd.DataFrame:
    """Moves from step t to t + 1 of the same proof whose areas differ (steps must both be present)."""
    d = df[KEY + [area_col]].dropna().sort_values(KEY)
    nxt = d.groupby("proof_id", sort=False).shift(-1)
    ok = (nxt["step"] == d["step"] + 1) & (nxt[area_col].astype(str) != d[area_col].astype(str))
    pairs = pd.DataFrame({"from_area": d.loc[ok, area_col].to_numpy(), "to_area": nxt.loc[ok, area_col].to_numpy()})
    if pairs.empty:
        return pd.DataFrame({"from_area": [], "to_area": [], "count": []}).astype({"count": int})
    out = pairs.groupby(["from_area", "to_area"]).size().rename("count").reset_index()
    return out.sort_values("count", ascending=False, kind="stable").reset_index(drop=True)


