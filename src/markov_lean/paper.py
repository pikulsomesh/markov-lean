def table_search_tex(table: pd.DataFrame) -> str:
    """Table 3 from the runs: one row per condition (baseline first), one column per benchmark, pass@1 in %."""
    benches = list(dict.fromkeys(table["benchmark"]))
    conds = list(dict.fromkeys(table["condition"]))
    if "lm" in conds:
        conds = ["lm"] + [c for c in conds if c != "lm"]
    known = [c for c in CONDITION_LABELS if c in conds]
    conds = known + [c for c in conds if c not in CONDITION_LABELS]
    head = " & ".join(BENCHMARK_LABELS.get(b, tex_escape(b)) for b in benches)
    lines = [r"\begin{tabular}{l" + "c" * len(benches) + "}", r"  \toprule", f"  Prior & {head} \\\\", r"  \midrule"]
    t = table.set_index(["benchmark", "condition"])
    for c in conds:
        vals = []
        for b in benches:
            v = t["pass@1"].get((b, c), np.nan) if "pass@1" in t.columns else np.nan
            vals.append(tex_num(100 * v, 1) if _finite(v) else r"\tbd")
        label = CONDITION_LABELS.get(c, (tex_escape(c), c))[0]
        lines.append(f"  {label} & " + " & ".join(vals) + r" \\")
    lines += [r"  \bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


