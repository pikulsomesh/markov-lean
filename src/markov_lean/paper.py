"""Rebuild the paper's figures, tables and headline numbers from whatever results exist.

``markov-lean paper --results results --paper paper``

The command looks under ``--results`` for the folders the other commands write,
uses every one it finds, and leaves the synthetic preview in place for anything
that has not run yet.  It makes no API calls and launches nothing.

Inputs (each optional; a ``--<name>`` flag picks a folder instead of the search):

| input | written by | found at |
|---|---|---|
| pilot | ``markov-lean pilot`` | ``<results>/*/pilot_report.json`` on real data, labelled folders first, then the highest-numbered |
| synthetic | ``markov-lean pilot`` on ``data.source: synthetic`` | the same glob, ``data.source == synthetic`` |
| full | ``markov-lean full`` | ``<results>/*/full_report.json`` |
| msm | either of the above | ``<full>/msm`` if it exists, else ``<pilot>/msm`` |
| search | ``markov-lean search-eval`` | the first ``<results>/*`` holding ``<benchmark>/<condition>/seed<k>/summary.jsonl`` |
| robustness | ``markov-lean robustness`` | ``<pilot>/robustness`` or ``<results>/robustness`` |
| significance | ``markov-lean significance`` | ``<pilot>/significance`` or ``<results>/significance`` |
| bridges | ``markov-lean bridges`` | ``<results>/bridges`` or ``<pilot>/bridges`` |
| switches | ``markov-lean switches`` | ``<pilot>/switches``, ``<results>/switches`` or ``<full>/switches`` |
| premise | ``markov-lean premise-labels`` | ``<results>/premise-switches/proofs_8plus/switches/train``, else ``.../all_proofs/switches/train`` |
| accuracy | ``markov-lean judge-accuracy --out`` | ``<pilot>/judge_accuracy`` or ``<results>/judge_accuracy`` |

Outputs in ``<paper>/figures/`` (what ``\\maybefigure`` and ``\\resultstable`` read):

* ``<name>.pdf`` for each paper figure that has real inputs, drawn at the width it prints at;
  ``chapman_kolmogorov_diagonal.pdf`` (main text) and ``chapman_kolmogorov.pdf`` (appendix) both come from the
  model's ``ck_test.csv``;
* ``search_ablation.pdf`` only once a search run has the area-prior condition; until then the figure is
  withheld (an earlier one is removed) and the paper leaves it out;
* ``switches.pdf``, redrawn from the switches run's results (with the premise rows when there is a premise
  run), or copied as it is from a run that kept only its figure;
* ``table_data.tex``, ``table_areas.tex``, ``table_search.tex``, ``table_switches.tex``: the tables'
  ``tabular`` bodies, with a red dash (``\\tbd``) in every cell still waiting on a run;
* ``results_macros.tex``: ``\\newcommand`` for every headline number the text
  uses (``\\resMacroNMI`` and so on), a red dash where the number is missing;
* extras that the text does not use yet, copied as they are: ``bridges.pdf``,
  ``robustness_<name>.pdf``, and every ``.tex`` table and ``.pdf`` figure of
  ``markov-lean search-report`` in ``<search>/report`` as ``search_<name>``.

The preview versions of the tables and macros (red dashes only) are rewritten in
``<paper>/figures/preview/`` on every run, so they always match the code; the
preview figures are those of ``scripts/preview_figures.py`` (``--redraw-previews``
redraws them).  A table or macros file with no real number in it is not written,
and an old generated one is removed, so the paper never shows stale numbers as
real.  The command prints one line per item: ``real``, ``preview``, ``withheld``
(a figure the paper leaves out until its run exists), or ``earlier`` (a real
figure from an earlier build that this run could not redraw).
"""

