def _headline_value(h: dict, key: str):
    if "." in key:
        k, i = key.rsplit(".", 1)
        v = h.get(k)
        return v[int(i)] if isinstance(v, (list, tuple)) and len(v) > int(i) else None
    return h.get(key)


def switch_macro_value(x, fmt: str) -> str:
    if not _finite(x):
        return r"\tbd"
    if fmt == "int":
        return tex_int(x)
    if fmt == "pct":
        return tex_num(100 * float(x), 1)
    if fmt == "p":
        return tex_num(x, 3)
    return tex_num(x, int(fmt[3:]))


def macros_tex(values: dict[str, tuple[str, str]], stamp: str | None = None,
               names: dict[str, str] | None = None) -> str:
    """``\\newcommand`` for every name in ``MACROS``; ``values`` maps a name to (TeX value, source)."""
    lines = [HEADER + (f" on {stamp}." if stamp else " (preview: every number still waits on a run)."),
             "% Do not edit by hand; rerun the command. Missing numbers print as a red dash (\\tbd)."]
    for name, what in (names or MACROS).items():
        val, source = values.get(name, (r"\tbd", ""))
        note = f"{what}" + (f"; from {source}" if source else "")
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}  % {note}")
    return "\n".join(lines) + "\n"


